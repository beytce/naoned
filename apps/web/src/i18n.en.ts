/** "1 order", "2 orders", "0 orders". */
const s = (n: number) => (n === 1 ? "" : "s");
/** 1st, 2nd, 3rd, 4th, 11th, 21st… */
export const ordinal = (n: number) => {
  const tens = n % 100;
  if (tens >= 11 && tens <= 13) return `${n}th`;
  return `${n}${["th", "st", "nd", "rd"][n % 10] ?? "th"}`;
};

